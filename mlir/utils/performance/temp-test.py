def add_numbers(a, b):
    """
    Add two numbers together.

    Args:
        a: First number
        b: Second number

    Returns:
        The sum of a and b
    """
    return a + b


if __name__ == "__main__":
    # Example usage - commit adfter
    result = add_numbers(5, 3)
    print(f"5 + 3 = {result}")

    result = add_numbers(10.5, 2.3)
    print(f"10.5 + 2.3 = {result}")
