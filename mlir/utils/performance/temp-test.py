def addNumbers(a, b):
    """
    Add two numbers together.
    
    Args:
        a: First number
        b: Second number
    
    Returns:
        The sum of a and b
    """
    return a + b


if __name__ == "__main__":
    # Example usage
    result = addNumbers(5, 3)
    print(f"5 + 3 = {result}")

    result = addNumbers(10.5, 2.3)
    print(f"10.5 + 2.3 = {result}")
